
BEGIN;

CREATE TABLE IF NOT EXISTS public.patient_appeal (
    id_appeal integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patient integer NOT NULL,
    id_responsible_user integer NULL,

    subject_appeal varchar(200) NOT NULL,
    description_appeal text NOT NULL,
    type_appeal varchar(30) NOT NULL,
    category_appeal varchar(100) NOT NULL,
    status_appeal varchar(30) NOT NULL DEFAULT 'Новое',

    created_appeal timestamp without time zone NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    due_date_appeal date NULL,
    updated_appeal timestamp without time zone NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT patient_appeal_patient_fk
        FOREIGN KEY (id_patient)
        REFERENCES public.patient(id_patient)
        ON DELETE RESTRICT,

    CONSTRAINT patient_appeal_responsible_user_fk
        FOREIGN KEY (id_responsible_user)
        REFERENCES public."user"(id_user)
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.patient_appeal_history (
    id_history integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_appeal integer NOT NULL,
    id_user integer NULL,

    action_history varchar(100) NOT NULL,
    details_history text NULL,
    created_history timestamp without time zone NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT patient_appeal_history_appeal_fk
        FOREIGN KEY (id_appeal)
        REFERENCES public.patient_appeal(id_appeal)
        ON DELETE CASCADE,

    CONSTRAINT patient_appeal_history_user_fk
        FOREIGN KEY (id_user)
        REFERENCES public."user"(id_user)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_patient_appeal_patient
    ON public.patient_appeal(id_patient);

CREATE INDEX IF NOT EXISTS idx_patient_appeal_status
    ON public.patient_appeal(status_appeal);

CREATE INDEX IF NOT EXISTS idx_patient_appeal_category
    ON public.patient_appeal(category_appeal);

CREATE INDEX IF NOT EXISTS idx_patient_appeal_due_date
    ON public.patient_appeal(due_date_appeal);

CREATE INDEX IF NOT EXISTS idx_patient_appeal_responsible_user
    ON public.patient_appeal(id_responsible_user);

CREATE INDEX IF NOT EXISTS idx_patient_appeal_history_appeal_created
    ON public.patient_appeal_history(id_appeal, created_history);

COMMIT;
